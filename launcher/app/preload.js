'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('umk3', {
    platform: process.platform,
    root: () => ipcRenderer.invoke('root:get'),
    logo: () => ipcRenderer.invoke('logo:get'),
    hero: () => ipcRenderer.invoke('hero:get'),
    loadConfig: () => ipcRenderer.invoke('config:load'),
    saveConfig: delta => ipcRenderer.invoke('config:save', delta),
    browseIpa: () => ipcRenderer.invoke('ipa:browse'),
    browseFrame: () => ipcRenderer.invoke('frame:browse'),
    startBuild: ipa => ipcRenderer.invoke('build:start', ipa),
    cancelBuild: () => ipcRenderer.invoke('build:cancel'),
    play: () => ipcRenderer.invoke('play'),
    loadProfile: name => ipcRenderer.invoke('profile:load', name),
    updateProfile: fields => ipcRenderer.invoke('profile:update', fields),
    resetProfile: name => ipcRenderer.invoke('profile:reset', name),
    profileIcon: i => ipcRenderer.invoke('profile:icon', i),
    profileIconAlt: i => ipcRenderer.invoke('profile:iconAlt', i),
    glyphs: () => ipcRenderer.invoke('glyphs:all'),
    listPads: () => ipcRenderer.invoke('pads:list'),
    listMonitors: () => ipcRenderer.invoke('monitors:list'),
    close: () => ipcRenderer.invoke('window:close'),
    relaunch: () => ipcRenderer.invoke('app:relaunch'),
    minimize: () => ipcRenderer.invoke('window:minimize'),
    maximize: () => ipcRenderer.invoke('window:maximize'),
    fullscreen: () => ipcRenderer.invoke('window:fullscreen'),
    onBuildData: cb => ipcRenderer.on('build:data', (_e, d) => cb(d)),
    checkUpdate: () => ipcRenderer.invoke('update:check'),
    installUpdate: () => ipcRenderer.invoke('update:install'),
    updateResult: () => ipcRenderer.invoke('update:result'),
    onUpdateProgress: cb => ipcRenderer.on('update:progress', (_e, d) => cb(d)),
    onGameClosed: cb => ipcRenderer.on('game:closed', () => cb()),
    modsList: () => ipcRenderer.invoke('mods:list'),
    modsSave: order => ipcRenderer.invoke('mods:save', order),
    modsCreate: fields => ipcRenderer.invoke('mods:create', fields),
    modsInfo: (folder, fields) => ipcRenderer.invoke('mods:info', folder, fields),
    modsPut: (folder, file, bytes) => ipcRenderer.invoke('mods:put', folder, file, bytes),
    modsAdd: folder => ipcRenderer.invoke('mods:add', folder),
    modsOpen: folder => ipcRenderer.invoke('mods:open', folder),
    modsTrash: folder => ipcRenderer.invoke('mods:trash', folder),
    resFiles: () => ipcRenderer.invoke('res:files'),
    resRead: (rel, layer) => ipcRenderer.invoke('res:read', rel, layer),
    modsCover: (folder, png) => ipcRenderer.invoke('mods:cover', folder, png),
    modsDataRead: folder => ipcRenderer.invoke('mods:dataRead', folder),
    modsDataWrite: (folder, entries) => ipcRenderer.invoke('mods:dataWrite', folder, entries),
    gameTables: () => ipcRenderer.invoke('game:tables'),
    pickFile: kind => ipcRenderer.invoke('file:pick', kind),
    exportSave: (sub, files) => ipcRenderer.invoke('export:save', sub, files),
    exportOpen: sub => ipcRenderer.invoke('export:open', sub),
    shot: () => ipcRenderer.invoke('shot:capture'),
    debugLayout: payload => ipcRenderer.invoke('debug:layout', payload),
    replaysList: () => ipcRenderer.invoke('replays:list'),
    replaysKeep: name => ipcRenderer.invoke('replays:keep', name),
    replaysDelete: (folder, name) => ipcRenderer.invoke('replays:delete', folder, name),
    replaysImport: () => ipcRenderer.invoke('replays:import'),
    replaysExport: (folder, name) => ipcRenderer.invoke('replays:export', folder, name),
    replaysOpen: () => ipcRenderer.invoke('replays:open'),
    replaysPlay: (folder, name) => ipcRenderer.invoke('replays:play', folder, name),
});