'use strict';

const fs = require('fs');
const path = require('path');
const { loadMachO } = require('./macho');

const LEVEL_INFO = '_Level_Info';
const POOL_AFTER = '_CurrentScene';

function hex2(n) {
    return '0x' + n.toString(16).padStart(2, '0');
}
function hex3(n) {
    return '0x' + n.toString(16).padStart(3, '0');
}
function hex8(n) {
    return '0x' + (n >>> 0).toString(16).padStart(8, '0');
}

/**
 * Extracts anonymous level info string pool and relocations.
 * @param {Buffer|string} machoInput
 * @param {string} outPath
 * @param {string} [sourceName]
 */
function extractLevelInfo(machoInput, outPath, sourceName = 'UMK3') {
    const { data, base, m } = loadMachO(machoInput);

    const syms = new Map();
    for (const s of m.symbols()) {
        if ((s.n_type & 0xe0) === 0 && (s.n_type & 0x0e) === 0x0e) {
            if (!syms.has(s.name)) {
                syms.set(s.name, s.n_value);
            }
        }
    }

    if (!syms.has(LEVEL_INFO)) throw new Error(`Symbol ${LEVEL_INFO} not found in binary`);
    if (!syms.has(POOL_AFTER)) throw new Error(`Symbol ${POOL_AFTER} not found in binary`);

    const info = syms.get(LEVEL_INFO);
    const after = syms.get(POOL_AFTER);
    const allValues = Array.from(syms.values());
    const later = allValues.filter(v => v > info).sort((a, b) => a - b);
    const info_size = later[0] - info;
    const pool_lo = after + 4;
    const pool_hi = info;

    if (allValues.some(v => pool_lo <= v && v < pool_hi)) {
        throw new Error('a symbol inside the string pool: the layout changed');
    }

    const sect = m.sectionForAddr(info);
    if (!sect || sect.segname !== '__DATA' || sect.sectname !== '__data') {
        throw new Error(`${LEVEL_INFO} is not in __DATA,__data`);
    }

    function at(addr, n) {
        const s = m.sectionForAddr(addr);
        const o = base + s.offset + addr - s.addr;
        return data.subarray(o, o + n);
    }

    const pool = at(pool_lo, pool_hi - pool_lo);
    const relocs = [];
    for (let off = 0; off <= info_size - 4; off += 4) {
        const w = at(info + off, 4).readUInt32LE(0);
        if (pool_lo <= w && w < pool_hi) {
            relocs.push([off, w - pool_lo]);
        }
    }

    if (relocs.length === 0) {
        throw new Error('no Level_Info word points into the pool');
    }

    const out = [];
    out.push(`/* Generated by tools/level_info.py from ${path.basename(sourceName)} -- game data, do not commit. */`);
    out.push('#include <stdint.h>\n');
    out.push('/* 32-bit, or a 64-bit build that keeps the game below 4 GB (UMK3_LOW32) */');
    out.push('#ifndef UMK3_LOW32');
    out.push('typedef char umk3_level_info_needs_32bit[sizeof(void *) == 4 ? 1 : -1];');
    out.push('#endif\n');
    out.push(`extern char Level_Info[];  /* ${hex8(info)}, ${info_size} bytes */\n`);
    out.push(`/* ${hex8(pool_lo)}..${hex8(pool_hi)}: the anonymous strings after ${POOL_AFTER.slice(1)} */`);
    out.push(`static char pool[${pool.length}] = {`);
    for (let i = 0; i < pool.length; i += 16) {
        const slice = pool.subarray(i, Math.min(i + 16, pool.length));
        const hexes = [];
        for (let b of slice) hexes.push(hex2(b));
        out.push('    ' + hexes.join(', ') + ',');
    }
    out.push('};\n');

    out.push(`static const uint16_t reloc_off[${relocs.length}] = {`);
    for (let i = 0; i < relocs.length; i += 8) {
        const chunk = relocs.slice(i, i + 8);
        out.push('    ' + chunk.map(r => hex3(r[0])).join(', ') + ',');
    }
    out.push('};');

    out.push(`static const uint16_t reloc_pool[${relocs.length}] = {`);
    for (let i = 0; i < relocs.length; i += 8) {
        const chunk = relocs.slice(i, i + 8);
        out.push('    ' + chunk.map(r => hex3(r[1])).join(', ') + ',');
    }
    out.push('};\n');

    out.push('void umk3_relocate_level_info(void)\n{');
    out.push('    unsigned i;\n');
    out.push(`    for (i = 0; i < ${relocs.length}; i++)`);
    out.push('        *(uint32_t *)(Level_Info + reloc_off[i]) =');
    out.push('            (uint32_t)(uintptr_t)(pool + reloc_pool[i]);');
    out.push('}');

    const content = out.join('\n') + '\n';
    if (outPath) {
        fs.mkdirSync(path.dirname(outPath), { recursive: true });
        fs.writeFileSync(outPath, content, { encoding: 'utf-8' });
    }
    return { relocsCount: relocs.length, poolSize: pool.length, content };
}

module.exports = { extractLevelInfo };
