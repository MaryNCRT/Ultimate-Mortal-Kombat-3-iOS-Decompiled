'use strict';

const fs = require('fs');
const path = require('path');
const { loadMachO } = require('./macho');

const SEQ_LO = 0x000de242; // the lowest address in seq_lookup's table

function hex4(n) {
    return '0x' + n.toString(16).padStart(4, '0');
}
function hex8(n) {
    return '0x' + (n >>> 0).toString(16).padStart(8, '0');
}

/**
 * Extracts special-move playback scripts.
 * @param {Buffer|string} machoInput
 * @param {string} outPath
 * @param {string} [sourceName]
 */
function extractSeqData(machoInput, outPath, sourceName = 'UMK3') {
    const { data, base, m } = loadMachO(machoInput);

    const sect = m.sectionForAddr(SEQ_LO);
    if (!sect || sect.segname !== '__TEXT' || sect.sectname !== '__const') {
        throw new Error(`${hex8(SEQ_LO)} is not in __TEXT,__const: the layout changed`);
    }

    const hi = sect.addr + sect.size;
    const off = base + sect.offset + SEQ_LO - sect.addr;
    let blob = data.subarray(off, off + hi - SEQ_LO);

    const out = [];
    out.push(`/* Generated by tools/seq_data.py from ${path.basename(sourceName)} -- game data, do not commit. */`);
    out.push('#include <stddef.h>\n');
    out.push(`/* ${hex8(SEQ_LO)}..${hex8(hi)}, __TEXT,__const */`);
    out.push(`static const unsigned short seq_words[${Math.floor((blob.length + 1) / 2)}] = {`);

    const paddedLen = blob.length % 2 !== 0 ? blob.length + 1 : blob.length;
    const words = [];
    for (let i = 0; i < paddedLen; i += 2) {
        const b0 = blob[i];
        const b1 = i + 1 < blob.length ? blob[i + 1] : 0;
        words.push(b0 | (b1 << 8));
    }

    for (let i = 0; i < words.length; i += 12) {
        const chunk = words.slice(i, i + 12);
        out.push('    ' + chunk.map(hex4).join(', ') + ',');
    }
    out.push('};\n');

    out.push('const unsigned char *umk3_seq_addr(unsigned long ios_address)\n{');
    out.push(`    if (ios_address < ${hex8(SEQ_LO)}ul || ios_address >= ${hex8(hi)}ul)`);
    out.push('        return NULL;');
    out.push(`    return (const unsigned char *)seq_words + (ios_address - ${hex8(SEQ_LO)}ul);`);
    out.push('}');

    const content = out.join('\n') + '\n';
    if (outPath) {
        fs.mkdirSync(path.dirname(outPath), { recursive: true });
        fs.writeFileSync(outPath, content, { encoding: 'utf-8' });
    }
    return { bytesCount: blob.length, content };
}

module.exports = { extractSeqData };
