"""Compiles the fixed-function shaders and writes them into the C headers the
backends include (../rgl_shaders_vk.h, ../rgl_shaders_d3d12.h). Run it after
changing ff.vert, ff.frag or ff.hlsl; the headers are committed, so the game's
own build needs neither tool.

    python build.py <glslang.exe> <fxc.exe>

glslang (Khronos, 16.6.0) makes the SPIR-V; fxc (Windows SDK) the DXBC,
shader model 5.1.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def run(*a):
    subprocess.run(a, check=True, cwd=HERE)


def c_array(name, data, word):
    out = []
    if word == 4:
        vals = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
        out.append('static const unsigned int %s[%d] = {' % (name, len(vals)))
        for i in range(0, len(vals), 6):
            out.append('    ' + ', '.join('0x%08x' % v for v in vals[i:i + 6]) + ',')
    else:
        out.append('static const unsigned char %s[%d] = {' % (name, len(data)))
        for i in range(0, len(data), 12):
            out.append('    ' + ', '.join('0x%02x' % v for v in data[i:i + 12]) + ',')
    out.append('};')
    return '\n'.join(out)


def write(path, head, arrays):
    with open(path, 'w', newline='\n') as f:
        f.write(head)
        for name, data, word in arrays:
            f.write(c_array(name, data, word) + '\n\n')


def main():
    glslang, fxc = sys.argv[1], sys.argv[2]
    run(glslang, '-V', 'ff.vert', '-o', 'ff.vert.spv')
    run(glslang, '-V', 'ff.frag', '-o', 'ff.frag.spv')
    run(fxc, '/nologo', '/T', 'vs_5_1', '/E', 'vs', '/O3', '/Fo', 'ff_vs.cso', 'ff.hlsl')
    run(fxc, '/nologo', '/T', 'ps_5_1', '/E', 'ps', '/O3', '/Fo', 'ff_ps.cso', 'ff.hlsl')
    rd = lambda n: open(os.path.join(HERE, n), 'rb').read()
    write(os.path.join(HERE, '..', 'rgl_shaders_vk.h'),
          '/* Generated by render/shaders/build.py from ff.vert and ff.frag: SPIR-V. */\n\n',
          [('k_vk_vs', rd('ff.vert.spv'), 4), ('k_vk_fs', rd('ff.frag.spv'), 4)])
    write(os.path.join(HERE, '..', 'rgl_shaders_d3d12.h'),
          '/* Generated by render/shaders/build.py from ff.hlsl: DXBC, shader model 5.1. */\n\n',
          [('k_dx_vs', rd('ff_vs.cso'), 1), ('k_dx_ps', rd('ff_ps.cso'), 1)])
    for n in ('ff.vert.spv', 'ff.frag.spv', 'ff_vs.cso', 'ff_ps.cso'):
        os.remove(os.path.join(HERE, n))


if __name__ == '__main__':
    main()
