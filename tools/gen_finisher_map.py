"""
gen_finisher_map.py -- writes src/runtime/fatal_trainer_map.h for the
FATALITY TRAINER (src/runtime/fatal_trainer.c).

The fight reads a button through a per-character routine (the ochar_*_close
and ochar_*_open tables, indexed by the character number, made from the .ipa
into build/logic_tables.c). Each routine hands one or more secret-move tables
(sm_*) to secret_move_search, sometimes through a helper. Which tables a
routine reaches is a fact of the decompiled code in src/decomp/gamecode/logic,
so it is read from there: every function whose body names an sm_ table, or
calls one that does, gets a row { the routine, its tables }.

The header holds names only -- no data of the game: the trainer looks a
routine up by its address at run time and reads the tables themselves.

    python tools/gen_finisher_map.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGIC = os.path.join(ROOT, "src", "decomp", "gamecode", "logic")
OUT = os.path.join(ROOT, "src", "runtime", "fatal_trainer_map.h")

DEF = re.compile(r"^(?:static\s+)?(?:void|long|int)\s+([a-z_][a-z0-9_]*)\s*\(([^;{]*)$",
                 re.M)


def functions(text):
    """name -> body, for every top-level definition"""
    out = {}
    static = set()
    for m in DEF.finditer(text):
        name = m.group(1)
        start = text.find("{", m.end())
        if start < 0 or text[m.end():start].strip().endswith(";"):
            continue
        # the body runs to the first closing brace in column 0
        end = text.find("\n}", start)
        if end < 0:
            continue
        out[name] = text[start:end]
        if text[m.start():m.end()].startswith("static"):
            static.add(name)
    return out, static


def main():
    bodies = {}
    static = set()
    for fn in sorted(os.listdir(LOGIC)):
        if fn.endswith(".c"):
            t = open(os.path.join(LOGIC, fn), encoding="utf-8", errors="replace").read()
            b, s = functions(t)
            for k, v in b.items():
                bodies.setdefault(k, v)
            static |= s

    direct = {}
    calls = {}
    for name, body in bodies.items():
        direct[name] = set(re.findall(r"\b(sm_[a-z0-9_]+)\b", body))
        calls[name] = set(re.findall(r"\b([a-z_][a-z0-9_]*)\s*\(", body)) & set(bodies)

    def reach(name, seen):
        if name in seen:
            return set()
        seen.add(name)
        r = set(direct.get(name, ()))
        for c in calls.get(name, ()):
            if c != "secret_move_search":
                r |= reach(c, seen)
        return r

    rows = []
    for name in sorted(bodies):
        if name in static or name.startswith("t_") or name.startswith("q_"):
            continue
        tabs = sorted(reach(name, set()))
        if tabs:
            rows.append((name, tabs))

    width = max(len(t) for _, t in rows)
    tables = sorted({t for _, ts in rows for t in ts})
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/gen_finisher_map.py from src/decomp/gamecode/logic:\n"
                " * each button routine of the fight and the secret-move tables it hands\n"
                " * to secret_move_search. Names only; do not edit. */\n\n")
        for n, _ in rows:
            f.write("void %s(void);\n" % n)
        f.write("\n")
        for t in tables:
            f.write("extern uint32_t %s[];\n" % t)
        f.write("\n#define FT_MAP_TABLES %d\n" % width)
        f.write("static const struct ft_map_row {\n"
                "    void (*fn)(void);\n"
                "    const uint32_t *tab[FT_MAP_TABLES];\n"
                "} ft_map[] = {\n")
        for n, ts in rows:
            f.write("    { %s, { %s } },\n" % (n, ", ".join(ts)))
        f.write("};\n\n")
        f.write("/* the tables' names, for UMK3_FT_VERIFY's listing */\n")
        f.write("static const struct { const uint32_t *tab; const char *name; } ft_map_names[] = {\n")
        for t in tables:
            f.write('    { %s, "%s" },\n' % (t, t))
        f.write("};\n")
    print("%d routines, %d tables -> %s" % (len(rows), len(tables), OUT))


if __name__ == "__main__":
    sys.exit(main())
